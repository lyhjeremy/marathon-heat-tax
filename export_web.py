"""
export_web.py: write assets/heat_data.js, the one data file the landing page and the
write-up read. Everything in it comes from tables/*.csv and model/heat_model.json.
Also fits the small proxy the forecast tool uses for climatology away from Boston.
"""
import json
import os

import numpy as np
import pandas as pd

from fetch_data import CACHE
from model_fit import ERAS, HOLDOUT, SERIES

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "tables")


def era_of(y):
    for i, (a, b, _) in enumerate(ERAS):
        if a <= y <= b:
            return i
    return len(ERAS) - 1


def daily_max_proxy(w):
    """Field-window course temperature against the day's maximum at the Wellesley point, so a
    daily-max climatology (one cheap archive call) can stand in for race-hour temperature."""
    xs, ys = [], []
    for y in w.year:
        js = json.load(open(os.path.join(CACHE, "weather", f"{y}.json")))
        t = [v for v in js[1]["hourly"]["temperature_2m"] if v is not None]
        xs.append(max(t)); ys.append(float(w.loc[w.year == y, "f_temp_f"].iloc[0]))
    b, a = np.polyfit(xs, ys, 1)
    res = np.array(ys) - (a + b * np.array(xs))
    return {"a": round(float(a), 3), "b": round(float(b), 4), "resid_sd_f": round(float(res.std(ddof=2)), 2),
            "n": len(xs)}


def main():
    w = pd.read_csv(os.path.join(TAB, "weather_by_year.csv"))
    f = pd.read_csv(os.path.join(TAB, "field_by_year.csv"))
    m = json.load(open(os.path.join(HERE, "model", "heat_model.json")))
    years = []
    for _, r in w.merge(f[["year", "n_listed", "share_women", "men_25th", "p50"]], on="year").iterrows():
        years.append({"y": int(r.year), "date": r.date, "era": era_of(r.year), "ho": int(r.year in HOLDOUT),
                      "te": r.e_temp_f, "tf": r.f_temp_f, "dp": r.f_dewpoint_f, "hi": r.f_heat_index_f,
                      "twe": r.e_tailwind_mph, "twf": r.f_tailwind_mph, "pr": r.f_precip_mm,
                      "n": int(r.n_listed)})
    series = {}
    for key, label, col, y0, wp, tier in SERIES:
        s = pd.read_csv(os.path.join(TAB, f"series_{key}.csv"))
        series[key] = {"label": label, "tier": tier,
                       "rows": [[int(r.year), round(r[col], 2), round(r.trend_min, 2), round(r.detrended_pct, 2),
                                 round(r.weather_pct, 2)] for _, r in s.iterrows()]}
    rob = pd.read_csv(os.path.join(TAB, "trend_robustness.csv"))
    robp = rob.pivot(index="series", columns="trend", values="beta_pct")
    sel = pd.read_csv(os.path.join(TAB, "model_selection.csv"))
    hold = pd.read_csv(os.path.join(TAB, "holdout_2015_2019.csv"))
    hsum = pd.read_csv(os.path.join(TAB, "holdout_summary.csv"))
    rec = pd.read_csv(os.path.join(TAB, "source_reconcile.csv"))
    ovn = pd.read_csv(os.path.join(TAB, "old_vs_new.csv"))
    slopes = pd.read_csv(os.path.join(TAB, "slopes_by_series.csv"))
    clim = w[w.year.between(1990, 2019)]
    out = {
        "meta": {"version": m["model_version"], "knot": m["knot_f"], "holdout": HOLDOUT,
                 "eras": [e[2] for e in ERAS]},
        "years": years,
        "series": series,
        "slopes": slopes.round(4).to_dict(orient="records"),
        "robustness": [{"series": k, **{c: (None if pd.isna(v) else round(float(v), 3)) for c, v in row.items()}}
                       for k, row in robp.iterrows()],
        "selection": sel.round(4).fillna("").to_dict(orient="records"),
        "holdout": hold.to_dict(orient="records"),
        "holdout_summary": hsum.to_dict(orient="records"),
        "reconcile": rec.to_dict(orient="records"),
        "old_vs_new": ovn.to_dict(orient="records"),
        "model": {
            "knot": m["knot_f"], "version": m["model_version"],
            "anchors": [{"series": a["series"], "label": a["label"], "typ": a["typical_min"], "pct": a["field_pct"],
                         "beta": a["beta"], "draws": a["draws"]} for a in m["anchors"]],
            "wind": {"pct": m["wind"]["pct_per_mph_headwind"], "draws": m["wind"]["draws_pct_per_mph_headwind"]},
            "bearing": m["course_bearing_deg"],
        },
        "clim_boston": {"years": clim.year.tolist(), "temp": clim.f_temp_f.tolist(), "dew": clim.f_dewpoint_f.tolist(),
                        "tail": clim.f_tailwind_mph.tolist()},
        "proxy": daily_max_proxy(w),
    }
    js = "/* Generated by export_web.py from tables/*.csv and model/heat_model.json. Do not edit. */\n"
    js += "window.HEAT_DATA = " + json.dumps(out, separators=(",", ":"), allow_nan=False) + ";\n"
    p = os.path.join(HERE, "assets", "heat_data.js")
    open(p, "w").write(js)
    print(p, os.path.getsize(p), "bytes; proxy", out["proxy"])


if __name__ == "__main__":
    main()
